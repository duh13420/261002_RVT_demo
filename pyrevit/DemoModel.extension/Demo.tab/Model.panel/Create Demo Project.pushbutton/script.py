# -*- coding: utf-8 -*-
"""Create a small demo Revit project in the active document."""

import os

from Autodesk.Revit.DB import (
    BuiltInCategory,
    CurveArray,
    CurveLoop,
    ElementId,
    FilteredElementCollector,
    Floor,
    FloorType,
    Grid,
    Line,
    Level,
    SaveAsOptions,
    TextNote,
    TextNoteOptions,
    TextNoteType,
    Transaction,
    ViewFamily,
    ViewFamilyType,
    ViewPlan,
    ViewSheet,
    Viewport,
    Wall,
    WallType,
    XYZ,
)
from Autodesk.Revit.DB.Structure import StructuralType
from System.Collections.Generic import List

try:
    from pyrevit import forms, revit
except ImportError:
    forms = None
    revit = None


DOC = __revit__.ActiveUIDocument.Document


def m_to_ft(value):
    return value * 3.280839895


def first_element(cls=None, category=None):
    collector = FilteredElementCollector(DOC)
    if cls:
        collector = collector.OfClass(cls)
    if category:
        collector = collector.OfCategory(category)
    for element in collector:
        return element
    return None


def first_symbol(category):
    collector = (
        FilteredElementCollector(DOC)
        .OfCategory(category)
        .WhereElementIsElementType()
    )
    for symbol in collector:
        return symbol
    return None


def ensure_symbol_active(symbol):
    if symbol and hasattr(symbol, "IsActive") and not symbol.IsActive:
        symbol.Activate()
        DOC.Regenerate()


def get_or_create_level(name, elevation_m):
    elevation = m_to_ft(elevation_m)
    for level in FilteredElementCollector(DOC).OfClass(Level):
        if level.Name == name:
            return level

    level = Level.Create(DOC, elevation)
    level.Name = name
    return level


def create_floor(curves, floor_type, level):
    try:
        loops = List[CurveLoop]()
        loop = CurveLoop()
        for curve in curves:
            loop.Append(curve)
        loops.Add(loop)
        return Floor.Create(DOC, loops, floor_type.Id, level.Id)
    except Exception:
        curve_array = CurveArray()
        for curve in curves:
            curve_array.Append(curve)
        return DOC.Create.NewFloor(curve_array, floor_type, level, False)


def create_plan_view(level):
    for view in FilteredElementCollector(DOC).OfClass(ViewPlan):
        if not view.IsTemplate and view.GenLevel and view.GenLevel.Id == level.Id:
            return view

    view_family_type = None
    for item in FilteredElementCollector(DOC).OfClass(ViewFamilyType):
        if item.ViewFamily == ViewFamily.FloorPlan:
            view_family_type = item
            break

    if view_family_type:
        view = ViewPlan.Create(DOC, view_family_type.Id, level.Id)
        view.Name = "Demo Plan - Level 1"
        return view

    return None


def add_text_note(view):
    if not view:
        return

    text_type = first_element(cls=TextNoteType)
    if not text_type:
        return

    try:
        options = TextNoteOptions(text_type.Id)
    except Exception:
        options = TextNoteOptions(ElementId.InvalidElementId)

    TextNote.Create(
        DOC,
        view.Id,
        XYZ(m_to_ft(1.0), m_to_ft(1.0), 0),
        "261002_RVT_demo generated by pyRevit",
        options,
    )


def add_sheet(view):
    if not view:
        return

    sheet = ViewSheet.Create(DOC, ElementId.InvalidElementId)
    sheet.Name = "Demo Sheet"
    sheet.SheetNumber = "A-001"

    try:
        Viewport.Create(DOC, sheet.Id, view.Id, XYZ(1.0, 1.0, 0))
    except Exception:
        pass


def set_project_info():
    info = DOC.ProjectInformation
    info.Name = "261002 RVT Demo Project"
    info.Number = "261002-DEMO"
    info.ClientName = "Demo Client"
    info.Address = "Demo Site"
    info.Status = "Generated for MCP/Revit demo"


def create_demo_model():
    level_1 = get_or_create_level("Demo Level 1", 0.0)
    level_2 = get_or_create_level("Demo Level 2", 3.2)

    wall_type = first_element(cls=WallType)
    floor_type = first_element(cls=FloorType)
    door_symbol = first_symbol(BuiltInCategory.OST_Doors)
    window_symbol = first_symbol(BuiltInCategory.OST_Windows)

    ensure_symbol_active(door_symbol)
    ensure_symbol_active(window_symbol)

    width = m_to_ft(10.0)
    depth = m_to_ft(8.0)
    height = m_to_ft(3.0)

    points = [
        XYZ(0, 0, 0),
        XYZ(width, 0, 0),
        XYZ(width, depth, 0),
        XYZ(0, depth, 0),
    ]
    wall_curves = [
        Line.CreateBound(points[0], points[1]),
        Line.CreateBound(points[1], points[2]),
        Line.CreateBound(points[2], points[3]),
        Line.CreateBound(points[3], points[0]),
    ]

    walls = []
    for curve in wall_curves:
        wall = Wall.Create(DOC, curve, wall_type.Id, level_1.Id, height, 0, False, False)
        walls.append(wall)

    if floor_type:
        create_floor(wall_curves, floor_type, level_1)

    if door_symbol and walls:
        DOC.Create.NewFamilyInstance(
            XYZ(width / 2, 0, 0),
            door_symbol,
            walls[0],
            level_1,
            StructuralType.NonStructural,
        )

    if window_symbol and len(walls) >= 4:
        DOC.Create.NewFamilyInstance(
            XYZ(width / 2, depth, m_to_ft(1.2)),
            window_symbol,
            walls[2],
            level_1,
            StructuralType.NonStructural,
        )
        DOC.Create.NewFamilyInstance(
            XYZ(0, depth / 2, m_to_ft(1.2)),
            window_symbol,
            walls[3],
            level_1,
            StructuralType.NonStructural,
        )

    grid_lines = [
        Line.CreateBound(XYZ(0, -m_to_ft(1.0), 0), XYZ(0, depth + m_to_ft(1.0), 0)),
        Line.CreateBound(XYZ(width, -m_to_ft(1.0), 0), XYZ(width, depth + m_to_ft(1.0), 0)),
        Line.CreateBound(XYZ(-m_to_ft(1.0), 0, 0), XYZ(width + m_to_ft(1.0), 0, 0)),
        Line.CreateBound(XYZ(-m_to_ft(1.0), depth, 0), XYZ(width + m_to_ft(1.0), depth, 0)),
    ]
    for grid_line in grid_lines:
        Grid.Create(DOC, grid_line)

    plan = create_plan_view(level_1)
    add_text_note(plan)
    add_sheet(plan)

    return level_2


def save_demo_file():
    output_dir = os.path.join(
        os.path.expanduser("~"),
        "Documents",
        "261002_RVT_demo_output",
    )
    if not os.path.isdir(output_dir):
        os.makedirs(output_dir)

    output_path = os.path.join(output_dir, "261002_RVT_demo_project.rvt")
    options = SaveAsOptions()
    options.OverwriteExistingFile = True
    DOC.SaveAs(output_path, options)
    return output_path


if DOC.IsFamilyDocument:
    raise Exception("Please run this command from a Revit project document, not a family document.")

transaction = Transaction(DOC, "Create 261002 RVT demo model")
transaction.Start()
try:
    set_project_info()
    create_demo_model()
    transaction.Commit()
except Exception:
    transaction.RollBack()
    raise

saved_path = save_demo_file()

if forms:
    forms.alert("Demo RVT created:\n\n{0}".format(saved_path), title="261002 RVT Demo")
else:
    print("Demo RVT created: {0}".format(saved_path))
